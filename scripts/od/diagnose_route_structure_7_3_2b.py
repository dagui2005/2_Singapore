"""
Step 7.3.2B — Route Structure / Path Choice Diagnosis

Use the existing MATSim plans.xml.gz + trips.csv.gz and the frozen
network_links_source_copy.csv to diagnose actual route structure.

This is diagnostic only:
  - no OD change
  - no network change
  - no capacity change
  - no lambda change
  - no population regeneration

Main outputs:
  reports/od_route_diagnosis_7_3_2b/
      route_agent_summary.csv
      route_class_summary.csv
      route_transition_matrix.csv
      route_od_consistency.csv
      route_diagnosis_summary.json
      STEP7_3_2B_REPORT.md (generated by the script)

Questions answered:
  1. What fraction of sampled vehicle routes use motorway?
  2. How much route length is motorway / motorway_link / primary / etc.?
  3. How often do routes contain motorway -> motorway_link -> motorway?
  4. How many OD pairs have multiple distinct routes in this it.0?
  5. Are the same motorway corridors repeatedly used?
"""

